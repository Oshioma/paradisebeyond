#!/usr/bin/env node
/**
 * Generate idempotent SQL that imports a source event's attendees into a
 * retreat's `retreat_contacts`, so a host can email them the photos/review
 * invite.
 *
 * Attendee data is PRIVATE (names + emails), so — unlike the photo import —
 * this reads a TOKEN-PROTECTED endpoint on the events app:
 *   GET /api/private/event-attendees?eventId=<uuid>
 *   Authorization: Bearer <SOURCE_TOKEN>
 * returning { event, contacts: [{ id, name, email, status }] }. The token is a
 * shared secret held only in CI secrets and the events app's env — nothing
 * about the attendees is ever exposed publicly.
 *
 * Usage:
 *   RETREAT=<slug|subdomain|host> SOURCE_EVENT=<uuid> \
 *   SOURCE_SITE=https://www.oshioma.com SOURCE_TOKEN=<secret> \
 *   node scripts/gen-import-contacts-sql.mjs > contacts.sql
 *   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f contacts.sql
 *
 * Re-runs update existing contacts (matched by source id) rather than
 * duplicating. Env SOURCE_ENDPOINT overrides SOURCE_SITE/SOURCE_EVENT.
 */

const die = (m) => { console.error(`✖ ${m}`); process.exit(1); };
const log = (m) => console.error(m);

const RETREAT = process.env.RETREAT || die("Set RETREAT");
const SOURCE_SITE = (process.env.SOURCE_SITE || "https://www.oshioma.com").replace(/\/$/, "");
const SOURCE_EVENT = process.env.SOURCE_EVENT;
const SOURCE_TOKEN = process.env.SOURCE_TOKEN || die("Set SOURCE_TOKEN (the shared secret for the attendees endpoint).");
const ENDPOINT =
  process.env.SOURCE_ENDPOINT ||
  (SOURCE_EVENT
    ? `${SOURCE_SITE}/api/private/event-attendees?eventId=${encodeURIComponent(SOURCE_EVENT)}`
    : die("Set SOURCE_EVENT (the source event UUID) or SOURCE_ENDPOINT."));

const label = (s) => String(s ?? "").toLowerCase().replace(/[^a-z0-9]/g, "");
const q = (s) => (s == null || s === "" ? "null" : `'${String(s).replace(/'/g, "''")}'`);

async function main() {
  log(`Fetching ${ENDPOINT}`);
  const res = await fetch(ENDPOINT, {
    headers: {
      authorization: `Bearer ${SOURCE_TOKEN}`,
      "user-agent": "ParadiseBeyondImport/1.0",
      accept: "application/json",
    },
  });
  if (res.status === 401 || res.status === 403) die(`Endpoint rejected the token (${res.status}). Check SOURCE_TOKEN matches the events app's secret.`);
  if (!res.ok) die(`Endpoint returned ${res.status}: ${(await res.text()).slice(0, 300)}`);
  let data;
  try { data = JSON.parse(await res.text()); } catch { die("Endpoint did not return JSON."); }

  const event = data.event ?? {};
  const contacts = Array.isArray(data.contacts) ? data.contacts : [];
  log(`Source event: "${event.name || event.slug || SOURCE_EVENT}" — ${contacts.length} attendee(s).`);
  if (!contacts.length) die("The endpoint returned no attendees.");

  // Dedupe within the batch: by source id, then by email (case-insensitive),
  // preferring a row that carries a name.
  const byRef = new Map();
  for (const c of contacts) {
    const ref = c.id != null ? String(c.id) : null;
    if (ref && !byRef.has(ref)) byRef.set(ref, c);
  }
  const seenEmail = new Set();
  const rows = [];
  let withEmail = 0;
  for (const c of byRef.values()) {
    const ref = c.id != null ? String(c.id) : null;
    const name = (c.name ?? "").toString().trim() || null;
    const email = (c.email ?? "").toString().trim().toLowerCase() || null;
    const status = (c.status ?? "").toString().trim() || null;
    if (email) {
      if (seenEmail.has(email)) continue;
      seenEmail.add(email);
      withEmail++;
    }
    rows.push(`(${q(ref)}, ${q(name)}, ${q(email)}, ${q(status)})`);
  }
  log(`  ${rows.length} unique contact(s), ${withEmail} with an email.`);
  if (!rows.length) die("No importable contacts.");

  const key = label(String(RETREAT).replace(/^https?:\/\//, "").split(".")[0]);
  console.log(`-- Import ${rows.length} attendees from ${ENDPOINT}
-- into retreat "${RETREAT}". Idempotent: re-runs update by source id.
-- Generated by scripts/gen-import-contacts-sql.mjs.
do $$
declare
  exp uuid;
begin
  select id into exp from experiences
  where lower(coalesce(subdomain, '')) = '${key}'
     or lower(regexp_replace(slug, '[^a-z0-9]', '', 'g')) = '${key}'
     or slug = ${q(RETREAT)}
  limit 1;
  if exp is null then
    raise exception 'No retreat matches "${key}"';
  end if;

  create temporary table _in (external_ref text, name text, email text, status text) on commit drop;
  insert into _in (external_ref, name, email, status) values
    ${rows.join(",\n    ")};

  insert into retreat_contacts (experience_id, external_ref, name, email, status, source)
  select exp, v.external_ref, v.name, v.email, v.status, 'import'
  from _in v
  on conflict (experience_id, external_ref) where external_ref is not null
  do update set name = excluded.name, email = excluded.email,
                status = excluded.status, updated_at = now();

  raise notice 'Imported/updated % contacts for retreat %', (select count(*) from _in), exp;
end $$;`);
}

main().catch((e) => die(e instanceof Error ? e.stack || e.message : String(e)));
