import type { Departure, Experience, ItineraryDay } from "@/lib/types";

const USD = "USD";

/** Build a departure. Dates are ISO (UTC). Prices in minor units (cents). */
function dep(
  id: string,
  startDate: string,
  endDate: string,
  priceFromMinor: number,
  capacity: number,
  spacesRemaining: number,
  depositMinor: number,
  status: Departure["status"] = "open",
): Departure {
  return {
    id,
    startDate,
    endDate,
    priceFromMinor,
    currency: USD,
    capacity,
    spacesRemaining,
    depositMinor,
    balanceDueDays: 45,
    status,
  };
}

function day(n: number, title: string, summary: string, items: string[]): ItineraryDay {
  return { day: n, title, summary, items: items.map((title) => ({ title })) };
}

